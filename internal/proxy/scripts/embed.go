// GetCombinedScript returns all JavaScript modules combined into a single script.
// The script is wrapped in appropriate tags and ordered for correct initialization.
// The result is cached after first call. Equivalent to
// GetCombinedScriptForRole(RoleFull).
func GetCombinedScript() string {
	return GetCombinedScriptForRole(RoleFull)
}

// GetCombinedScriptForRole returns the bundle flavour for the given frame
// role (RoleFull, RoleChrome, or RoleContent), built once and cached.
func GetCombinedScriptForRole(role Role) string {
	if s, ok := combinedScripts.Load(role); ok {
		return s.(string)
	}
	built := buildCombinedScript(role)
	s, _ := combinedScripts.LoadOrStore(role, built)
	return s.(string)
}

// buildCombinedScript assembles the modules for role in the dependency order
// defined by moduleOrder, skipping modules excluded from that role's bundle.
func buildCombinedScript(role Role) string {
	var sb strings.Builder

	// Main script block
	sb.WriteString("<script>\n")

	// The public bundle (RolePublic) is a hard-allowlisted, dev-control-free
	// artifact: it must ship NEITHER the html2canvas capture library NOR the
	// window.__devtool_* version marker, both of which are dev-surface tokens the
	// forbidden-symbol scan rejects. Every other role keeps today's behaviour.
	isPublic := role == RolePublic

	// html2canvas-pro (~211KB) is NO LONGER prepended to the always-injected
	// bundle. It blocked first paint of every proxied page and parsed in every
	// frame that never captured a screenshot. It is now served on demand from
	// /__devtool_html2canvas and injected only when a capture actually runs, via
	// window.__devtool_ensureHtml2canvas (html2canvas-loader.js, shipped in every
	// non-public bundle). This mirrors how axe-core is already lazy-loaded.

	sb.WriteString("(function() {\n")
	sb.WriteString("  'use strict';\n\n")

	if isPublic {
		// Public-namespaced version marker — deliberately NOT __devtool_* so the
		// public bundle stays provably free of the dev-control namespace.
		sb.WriteString("  // Version injected at build/runtime (public plane)\n")
		sb.WriteString("  window.__agnt_public_version = '")
		sb.WriteString(Version)
		sb.WriteString("';\n\n")
	} else {
		// Inject version as first thing in the script
		sb.WriteString("  // Version injected at build/runtime\n")
		sb.WriteString("  window.__devtool_version = '")
		sb.WriteString(Version)
		sb.WriteString("';\n\n")
	}

	// Load modules in dependency order from moduleOrder
	for _, m := range moduleOrder {
		if !includeInRole(m.name, role) {
			continue
		}
		sb.WriteString("  // ")
		sb.WriteString(m.name)
		sb.WriteString(" module\n")
		sb.WriteString(wrapModule(moduleScript[m.name]))
		sb.WriteString("\n\n")
	}

	sb.WriteString("})();\n")
	sb.WriteString("</script>\n")

	return sb.String()
}

// wrapModule removes the outer IIFE from a module since we're wrapping everything
// in a single IIFE. It also indents the code for readability.
func wrapModule(js string) string {
	// Remove leading/trailing whitespace
	js = strings.TrimSpace(js)

	// Remove outer IIFE wrapper if present: (function() { ... })();
	if strings.HasPrefix(js, "(function()") {
		// Find the matching closing
		depth := 0
		start := -1
		end := -1

		for i, c := range js {
			if c == '{' {
				if start == -1 {
					start = i + 1
				}
				depth++
			} else if c == '}' {
				depth--
				if depth == 0 {
					end = i
					break
				}
			}
		}

		if start != -1 && end != -1 {
			// Extract content between braces
			content := js[start:end]
			// Remove 'use strict' if present (we add it at the top level)
			content = strings.Replace(content, "'use strict';", "", 1)
			content = strings.Replace(content, `"use strict";`, "", 1)
			return strings.TrimSpace(content)
		}
	}

	return js
}

