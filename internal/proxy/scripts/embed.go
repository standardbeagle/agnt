// moduleRole classifies modules for the per-frame bundle split. Modules not
// listed here are SHARED and ship in every bundle. The full (RoleFull) bundle
// always includes every module regardless of this map.
//
// A module may only be RoleContent (excluded from the chrome bundle) if
// nothing shipping in the chrome bundle dereferences its exports at bundle
// eval. api.js is the main hazard: it hard-derefs
// overlay/inspection/tree/visual/layout/interactive/capture/accessibility/
// audit(-quality, which itself eval-derefs -dom/-css/-security/-performance/
// -utils)/voice/sketch/design/style-editor/indicator inside the
// window.__devtool literal, so those all stay shared even though most of
// them only ever do real work in the content frame. The modules below are
// safe: api.js either doesn't touch them, references them as plain values
// (`mutations: mutations`), or guards them (`wireframe ? … : fallback`,
// `window.__devtool_snapshot || {…}`), and core.js pre-installs a
// __devtool_diagnostics fallback. session/palette/toast/responsive(-mode)
// stay shared deliberately: session feeds page-session tracking from every
// frame, palette + toast are user surfaces in both frames, and the indicator
// toggles window.__devtool_responsive in its own (shell) window.
//
// A module may only be RoleChrome (excluded from the content bundle) if its
// content-side callers are covered: indicator-bridge replaces the indicator's
// nested-frame hotkey forwarding + addAttachment surface, walkthrough-proxy
// replaces walkthrough's non-host forwarding proxy, and api.js guards its
// indicator block with a not-loaded fallback.
