// Role identifies which per-frame bundle flavour to build. The proxy knows
// the frame role at injection time: the chrome-shell document is generated by
// BuildShellDocument (chrome), a wrapped content frame's request carries the
// frame marker (content), and everything else — unwrapped fallback, HTML
// fragments, passive embeds, legacy injection — gets the full bundle, which
// is byte-for-byte today's behaviour.
type Role string

const (
	// RoleFull is the complete bundle: every module (passive/legacy default).
	RoleFull Role = ""
	// RoleChrome is the shell bundle: shared + chrome-only modules, without
	// the content-only set.
	RoleChrome Role = "chrome"
	// RoleContent is the content-frame bundle: shared modules (including the
	// indicator-bridge / walkthrough-proxy forwarding stubs) + content-only
	// modules, without the chrome-only set.
	RoleContent Role = "content"
	// RolePublic is the HARD-ALLOWLISTED public bundle for the walkthrough-publish
	// plane (P4). Unlike RoleChrome/RoleContent — which are SUBTRACTIVE filters
	// over the full module set — RolePublic is built from an EXPLICIT ALLOWLIST
	// (rolePublicModules) and contains ONLY those members: the variant renderer,
	// the read-only walkthrough viewer, the feedback client, and the boot glue
	// that starts the viewer from the share token in the URL. It carries NONE
	// of the dev-control surface (no core WS/exec channel, no __devtool control
	// API, no audits/capture/inspection/design/indicator/authbreakout), ships no
	// html2canvas, and runs under `script-src 'self'` with no eval/inline. The
	// dependency-closure + forbidden-symbol tests in role_public_test.go fail the
	// build if a forbidden module ever enters this bundle.
	RolePublic Role = "public"
)

